
import argparse
import json
from pathlib import Path

import h5py
import numpy as np
import torch

# Reuse the exact architecture and target definitions used for training.
from train_mdn import MDN, mdn_nll, Y_IDX, Y_NAMES


INPUT_KEYS = [
    "input_temporal_intensity",
    "input_spectral_intensity",
    "output_temporal_intensity",
    "output_spectral_intensity",
]


def load_test_data(path):
    with h5py.File(path, "r") as hf:
        missing = [key for key in INPUT_KEYS + ["meta_parameters", "time_vector"]
                   if key not in hf]
        if missing:
            raise ValueError(f"Missing required HDF5 datasets: {missing}")

        # Same four-channel ordering as train_mdn.py.
        x = np.stack([hf[key][:] for key in INPUT_KEYS], axis=1).astype(np.float32)
        labels = hf["meta_parameters"][:].astype(np.float32)
        time_vector = hf["time_vector"][:].astype(np.float32)

    if labels.ndim != 2 or labels.shape[1] != 8:
        raise ValueError(
            f"Expected meta_parameters shape (N, 8); got {labels.shape}. "
            "Use a dataset generated by the supplied datasetgen.py."
        )
    if x.ndim != 3 or x.shape[1] != 4:
        raise ValueError(f"Expected input shape (N, 4, 2048); got {x.shape}.")
    if len(x) != len(labels):
        raise ValueError("Input sample count does not match label sample count.")
    if len(x) == 0:
        raise ValueError("Test dataset contains no samples.")
    if not np.isfinite(x).all() or not np.isfinite(labels).all():
        raise ValueError("Dataset contains NaN or infinite values.")

    y = labels[:, Y_IDX]
    pulse_type = labels[:, 7].astype(np.int64)
    if not np.isin(pulse_type, [0, 1]).all():
        raise ValueError("Pulse labels must be 0 (Gaussian) or 1 (sech).")
    return x, y, pulse_type, labels, time_vector


def main():
    parser = argparse.ArgumentParser(description="Evaluate a saved NLSE MDN checkpoint.")
    parser.add_argument("--model", default="mdn_run/best_mdn.pt")
    parser.add_argument("--data", default="nlse_tnn_test_independent.h5")
    parser.add_argument("--batch-size", type=int, default=64)
    parser.add_argument("--out", default="mdn_independent_test_results")
    args = parser.parse_args()

    model_path = Path(args.model)
    data_path = Path(args.data)
    if args.batch_size < 1:
        raise ValueError("--batch-size must be at least 1.")
    if not model_path.is_file():
        raise FileNotFoundError(f"Checkpoint not found: {model_path.resolve()}")
    if not data_path.is_file():
        raise FileNotFoundError(f"Test dataset not found: {data_path.resolve()}")

    # Checkpoints are generated by the user's local train_mdn.py script.
    try:
        checkpoint = torch.load(model_path, map_location="cpu", weights_only=False)
    except TypeError:
        checkpoint = torch.load(model_path, map_location="cpu")

    for key in ["model_state_dict", "x_mean", "x_std", "y_mean", "y_std"]:
        if key not in checkpoint:
            raise ValueError(
                f"Checkpoint is missing '{key}'. It may not have been saved by "
                "the supplied train_mdn.py."
            )

    x, y_true, pulse_true, labels, time_vector = load_test_data(data_path)

    # Apply training-set preprocessing from the checkpoint; never refit on test data.
    x_mean = np.asarray(checkpoint["x_mean"], dtype=np.float32)
    x_std = np.asarray(checkpoint["x_std"], dtype=np.float32)
    y_mean = np.asarray(checkpoint["y_mean"], dtype=np.float32)
    y_std = np.asarray(checkpoint["y_std"], dtype=np.float32)
    if x_mean.shape != (1, 4, 1) or x_std.shape != (1, 4, 1):
        raise ValueError(f"Unexpected saved input normalization shapes: {x_mean.shape}, {x_std.shape}")
    if y_mean.shape != (1, len(Y_IDX)) or y_std.shape != (1, len(Y_IDX)):
        raise ValueError(f"Unexpected saved target normalization shapes: {y_mean.shape}, {y_std.shape}")

    x_norm = ((x - x_mean) / np.maximum(x_std, 1e-6)).astype(np.float32)
    y_norm = ((y_true - y_mean) / np.maximum(y_std, 1e-8)).astype(np.float32)

    model = MDN(n_components=int(checkpoint.get("n_components", 5)))
    model.load_state_dict(checkpoint["model_state_dict"])
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model.to(device).eval()

    total_nll = 0.0
    all_pred = []
    all_pulse_pred = []
    with torch.no_grad():
        for start in range(0, len(x_norm), args.batch_size):
            end = min(start + args.batch_size, len(x_norm))
            xb = torch.from_numpy(x_norm[start:end]).to(device)
            yb = torch.from_numpy(y_norm[start:end]).to(device)
            logits, means, log_scales, type_logits = model(xb)
            n = end - start
            total_nll += mdn_nll(yb, logits, means, log_scales).item() * n

            # Mixture-weighted mean gives a point estimate for MAE/RMSE.
            weights = torch.softmax(logits, dim=1).unsqueeze(-1)
            pred_norm = (weights * means).sum(dim=1)
            pred_real = pred_norm.cpu().numpy() * y_std + y_mean
            all_pred.append(pred_real)
            all_pulse_pred.append(type_logits.argmax(dim=1).cpu().numpy())

    y_pred = np.concatenate(all_pred, axis=0)
    pulse_pred = np.concatenate(all_pulse_pred, axis=0)
    errors = y_pred - y_true
    mae = np.mean(np.abs(errors), axis=0)
    rmse = np.sqrt(np.mean(errors ** 2, axis=0))
    pulse_accuracy = float(np.mean(pulse_pred == pulse_true))

    confusion = np.zeros((2, 2), dtype=np.int64)
    for actual, predicted in zip(pulse_true, pulse_pred):
        confusion[int(actual), int(predicted)] += 1

    target_ranges = {
        "L_km": [10.0, 80.0],
        "beta2_ps2_km": [-25.0, -5.0],
        "gamma_W_km": [1.0, 5.0],
        "loss_dB_km": [0.18, 0.35],
        "P0_W": [0.01, 0.10],
        "T0_ps": [10.0, 30.0],
    }
    metrics = {
        "test_dataset": str(data_path.resolve()),
        "model_checkpoint": str(model_path.resolve()),
        "n_test_samples": int(len(x)),
        "device": str(device),
        "mdn_nll_normalized": float(total_nll / len(x)),
        "pulse_type_accuracy": pulse_accuracy,
        "pulse_type_confusion_matrix_rows_actual_cols_predicted": confusion.tolist(),
        "continuous_targets": {},
        "notes": [
            "No training or parameter updates are performed by this script.",
            "Input/target normalization is taken from the saved training checkpoint.",
            "MAE/RMSE use the mixture-weighted mean in original parameter units.",
            "D_ps_nm_km is derived from beta2 and is not independently predicted.",
            "A different LHS seed creates a fresh sample but does not alone prove zero overlap with training samples."
        ],
    }
    for i, name in enumerate(Y_NAMES):
        lo, hi = target_ranges[name]
        metrics["continuous_targets"][name] = {
            "MAE": float(mae[i]),
            "RMSE": float(rmse[i]),
            "MAE_percent_of_parameter_range": float(100.0 * mae[i] / (hi - lo)),
        }

    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "metrics.json").write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    np.savez_compressed(
        out_dir / "predictions.npz",
        y_true=y_true,
        y_pred=y_pred,
        pulse_type_true=pulse_true,
        pulse_type_pred=pulse_pred,
        meta_parameters=labels,
        time_vector=time_vector,
    )

    print(f"Test samples: {len(x)}")
    print(f"Device: {device}")
    print(f"Normalized MDN NLL: {metrics['mdn_nll_normalized']:.6f}")
    print(f"Pulse-type accuracy: {pulse_accuracy:.2%}")
    print("\nContinuous-target metrics (original units):")
    print(f"{'Target':<18} {'MAE':>12} {'RMSE':>12} {'MAE/range':>12}")
    for name in Y_NAMES:
        item = metrics["continuous_targets"][name]
        print(
            f"{name:<18} {item['MAE']:>12.6g} {item['RMSE']:>12.6g} "
            f"{item['MAE_percent_of_parameter_range']:>11.3f}%"
        )
    print("\nPulse-type confusion matrix (rows=actual [Gaussian, sech], columns=predicted [Gaussian, sech]):")
    print(confusion)
    print(f"\nResults saved to: {out_dir.resolve()}")
    print("Reminder: verify sample overlap against the actual training HDF5 before claiming strict independence.")


if __name__ == "__main__":
    main()